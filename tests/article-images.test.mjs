import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { embedArticleImages, restoreArticleImageReferences } from '../lib/article-images.mjs';
import { commitArticle } from '../lib/article-revisions.mjs';
import { validateArticle } from '../lib/article.mjs';
import sharp from 'sharp';

test('saved revisions embed real images, travel alone, and recover compact editable references', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'bloop-embedded-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  await mkdir(path.join(directory, 'assets'));
  const asset = { id: randomUUID(), file: randomUUID() + '.png', role: 'article' };
  const pixels = await sharp({ create: { width: 40, height: 20, channels: 3, background: '#658b7b' } }).png().toBuffer();
  await writeFile(path.join(directory, 'assets', asset.file), pixels);
  const job = { assets: [asset], text: '原始正文需要完整保留，不能因排版遗漏。' };
  const raw = `<section><p>${job.text}</p><img src="asset://${asset.id}" style="border-radius:24px;width:80%;margin:8px auto;"></section>`;
  const checked = validateArticle(raw, { assets: job.assets, source: job.text });
  assert.deepEqual(checked.errors, []);
  const saved = await commitArticle(directory, { html: checked.html, preview: '<article>' + checked.html + '</article>', submission: { title: '固定版本' }, job });
  const html = await readFile(saved.article, 'utf8');
  assert.ok(html.includes('data:image/png;base64,' + pixels.toString('base64')));
  assert.ok(!html.includes('src="assets/'));
  assert.ok(html.includes('border-radius:24px'));
  const restored = await restoreArticleImageReferences(html, path.dirname(saved.article), job.assets);
  assert.ok(!restored.includes('base64,'));
  assert.ok(restored.includes(`asset://${asset.id}`));
  assert.deepEqual(validateArticle(restored, { assets: job.assets, source: job.text }).errors, []);
  await rm(path.join(directory, 'assets'), { recursive: true });
  assert.equal(await readFile(saved.article, 'utf8'), html);
  assert.equal(await embedArticleImages(html, directory, job.assets), html);
  assert.ok(!(await readFile(saved.preview, 'utf8')).includes('src="assets/'));
  await assert.rejects(embedArticleImages('<img src="assets/../secret.png">', directory, [{file: '../secret.png'}]), /素材文件名无效/);
  const unknown = 'data:image/png;base64,unknown';
  const unregistered = await restoreArticleImageReferences(`<p>${job.text}</p><img src="${unknown}">`, path.dirname(saved.article), job.assets);
  assert.ok(validateArticle(unregistered, {assets: job.assets}).errors.length);
});
